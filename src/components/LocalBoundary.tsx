import { Component, type ReactNode } from 'react';

/** A failed optional surface must leave the rest of the guide usable. */
export class LocalBoundary extends Component<{ children: ReactNode; fallback: ReactNode }, { failed: boolean }> {
  state = { failed: false };
  static getDerivedStateFromError() { return { failed: true }; }
  render() { return this.state.failed ? this.props.fallback : this.props.children; }
}
